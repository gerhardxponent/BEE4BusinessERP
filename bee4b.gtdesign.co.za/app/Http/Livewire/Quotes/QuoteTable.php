    public function columns(): array
    {
        return [
            Column::add()
                ->title('ID')
                ->field('id')
                ->makeInputRange(),

            Column::add()
                ->title('NAME')
                ->field('quote_name', 'quotes.name')
                ->hidden()
                ->visibleInExport(true),

            Column::add()
                ->title('NAME')
                ->field('quote_link', 'quotes.name')
                ->sortable()
                ->searchable()
                ->makeInputText()
                ->visibleInExport(false),

            Column::add()
                ->title('CLIENT')
                ->field('client_name', 'clients.name')
                ->sortable()
                ->searchable()
                ->makeInputSelect(Clients::all(), 'name', 'clients.id'),

            Column::add()
                ->title('CREATED AT')
                ->field('created_at_formatted', 'created_at')
                ->searchable()
                ->sortable()
                ->makeInputDatePicker('created_at'),

            Column::add()
                ->title('UPDATED AT')
                ->field('updated_at_formatted', 'updated_at')
                ->searchable()
                ->sortable()
                ->makeInputDatePicker('updated_at'),

        ]
;
    }

