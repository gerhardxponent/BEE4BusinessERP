    * @return  \Illuminate\Database\Eloquent\Builder<\App\Models\Quote>|null
    */
    public function datasource(): ?Builder
    {
        return Quote::query()
            ->join('clients', function($clients) {
                $clients->on('quotes.client_id', '=', 'clients.id');
            })
            ->select([
                'quotes.id',
                'quotes.name AS quote_name',
                'clients.name AS client_name',
                'quotes.created_at',
                'quotes.updated_at'
            ]);
    }

