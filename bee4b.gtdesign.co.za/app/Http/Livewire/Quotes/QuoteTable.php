    |--------------------------------------------------------------------------
    | Make Datasource fields available to be used as columns.
    | You can pass a closure to transform/modify the data.
    |
    */
    public function addColumns(): ?PowerGridEloquent
    {
        return PowerGrid::eloquent()
            ->addColumn('id')
            ->addColumn('quote_name')
            ->addColumn('quote_link', function(Quote $model) {
                return '<a class="table-link" href="quotes/'.$model->id.'">'.$model->quote_name.'</a>';
            })
            ->addColumn('client_name') 
            ->addColumn('created_at_formatted', function(Quote $model) { 
                return Carbon::parse($model->created_at)->format('d/m/Y H:i:s');
            })
            ->addColumn('updated_at_formatted', function(Quote $model) { 
                return Carbon::parse($model->updated_at)->format('d/m/Y H:i:s');
            });
    }

